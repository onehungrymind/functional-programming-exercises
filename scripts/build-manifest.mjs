#!/usr/bin/env node
/**
 * Generates packages/exercises/src/manifest.ts from the exercise sets.
 *
 * Two files, split by when the shell needs them.
 *
 * manifest.ts is structure: which terms have exercises, how many rungs each has, what they
 * are called. The graph, the search, the curriculum order and the Practice count all need it
 * before anything is on screen, and it is small.
 *
 * notes.ts is the prose, and only the open drawer reads it. It is roughly six times the size
 * of the structure, so it is a separate module the drawer imports on demand rather than
 * something every visitor downloads to look at a graph.
 *
 * Neither file carries the `checks` functions, the solutions, or the broken variants; those
 * are the bulk of the content and live in the exercise sets, loaded with the Practice tab.
 *
 * Both are committed, and `npm run verify` fails if either has drifted from the sets, so
 * there is one source of truth and no way to forget to regenerate them.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/exercises/src/manifest.ts');
const NOTES_OUT = join(ROOT, 'packages/exercises/src/notes.ts');

const { exerciseSets, exerciseTermIds } = await import(
  new URL(`file://${join(ROOT, 'packages/exercises/src/index.ts')}`).href
);

export function buildManifest() {
  return exerciseTermIds.map((termId) => {
    const set = exerciseSets[termId];
    return {
      termId,
      rungs: set.rungs.map((r) => ({
        id: r.id,
        role: r.role,
        title: r.title,
        kind: r.kind,
        lang: r.lang ?? 'js',
      })),
    };
  });
}

/** The prose half, keyed by term. Loaded on demand, never in the initial bundle. */
export function buildNotes() {
  return Object.fromEntries(
    exerciseTermIds
      .filter((termId) => exerciseSets[termId].notes || exerciseSets[termId].typedNotes)
      .map((termId) => [
        termId,
        {
          notes: exerciseSets[termId].notes ?? null,
          typedNotes: exerciseSets[termId].typedNotes ?? null,
        },
      ]),
  );
}

const manifest = buildManifest();
const notes = buildNotes();

const body = `/**
 * Generated by scripts/build-manifest.mjs. Do not edit by hand.
 *
 * Structure only: which terms have exercises, how many rungs each has, and what they are
 * called. Everything the shell needs before anything is on screen. The prose lives in
 * ./notes.ts, which the drawer imports on demand, and the checks and solutions live in the
 * exercise sets. Run \`npm run build:manifest\` after changing an exercise set;
 * \`npm run verify\` fails if this has drifted.
 */

export interface ManifestRung {
  id: string;
  role: 'recognize' | 'guided' | 'implement' | 'break' | 'apply' | 'articulate';
  title: string;
  kind: 'choice' | 'expr' | 'code' | 'reveal';
  /** Which lap this rung belongs to. */
  lang: 'js' | 'ts';
}

export interface ManifestEntry {
  termId: string;
  rungs: ManifestRung[];
}

export const manifest: ManifestEntry[] = ${JSON.stringify(manifest, null, 2)};

export const manifestByTerm: Record<string, ManifestEntry> = Object.fromEntries(
  manifest.map((entry) => [entry.termId, entry]),
);

export const manifestTermIds: string[] = manifest.map((entry) => entry.termId);

export const hasExercises = (termId: string): boolean => termId in manifestByTerm;
`;

const notesBody = `/**
 * Generated by scripts/build-manifest.mjs. Do not edit by hand.
 *
 * The Learn prose, split out of the manifest because only an open drawer reads it and it is
 * several times the size of everything else the shell needs. Import it lazily.
 */

export interface ConceptNotes {
  /** Teaching this repo owns, rendered in Learn after the upstream entry. */
  notes: string | null;
  /** The second lap: the same concept with the types written down. */
  typedNotes: string | null;
}

export const conceptNotes: Record<string, ConceptNotes> = ${JSON.stringify(notes, null, 2)};
`;

const read = (path) => {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
};

const written = [];
if (read(OUT) !== body) {
  writeFileSync(OUT, body);
  written.push(`manifest.ts (${manifest.length} concepts)`);
}
if (read(NOTES_OUT) !== notesBody) {
  writeFileSync(NOTES_OUT, notesBody);
  written.push(`notes.ts (${Object.keys(notes).length} concepts)`);
}

console.log(
  written.length
    ? `\n  wrote packages/exercises/src/${written.join(', ')}\n`
    : `\n  manifest and notes are already up to date (${manifest.length} concepts)\n`,
);
