#!/usr/bin/env node
/**
 * Generates packages/exercises/src/manifest.ts from the exercise sets.
 *
 * The shell needs to know which terms have exercises, how many rungs each has, and what they
 * are called: enough for the Practice tab, its count, and the stepper. It does not need the
 * `checks` functions, the solutions, or the broken variants, and those are the bulk of the
 * content. Importing the sets directly put all of it in the initial bundle.
 *
 * The manifest is committed, and `npm run verify` fails if it has drifted from the sets, so
 * there is one source of truth and no way to forget to regenerate it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/exercises/src/manifest.ts');

const { exerciseSets, exerciseTermIds } = await import(
  new URL(`file://${join(ROOT, 'packages/exercises/src/index.ts')}`).href
);

export function buildManifest() {
  return exerciseTermIds.map((termId) => {
    const set = exerciseSets[termId];
    return {
      termId,
      rungs: set.rungs.map((r) => ({ id: r.id, role: r.role, title: r.title, kind: r.kind })),
    };
  });
}

const manifest = buildManifest();

const body = `/**
 * Generated by scripts/build-manifest.mjs. Do not edit by hand.
 *
 * Just enough for the shell to render the Practice tab, its done/total count, and the rung
 * stepper, without pulling in the checks, solutions, and broken variants that make up the
 * bulk of the content. Run \`npm run build:manifest\` after changing an exercise set;
 * \`npm run verify\` fails if this has drifted.
 */

export interface ManifestRung {
  id: string;
  role: 'recognize' | 'guided' | 'implement' | 'break' | 'apply' | 'articulate';
  title: string;
  kind: 'choice' | 'expr' | 'code' | 'reveal';
}

export interface ManifestEntry {
  termId: string;
  rungs: ManifestRung[];
}

export const manifest: ManifestEntry[] = ${JSON.stringify(manifest, null, 2)};

export const manifestByTerm: Record<string, ManifestEntry> = Object.fromEntries(
  manifest.map((entry) => [entry.termId, entry]),
);

export const manifestTermIds: string[] = manifest.map((entry) => entry.termId);

export const hasExercises = (termId: string): boolean => termId in manifestByTerm;
`;

const previous = (() => {
  try {
    return readFileSync(OUT, 'utf8');
  } catch {
    return null;
  }
})();

if (previous === body) {
  console.log(`\n  manifest is already up to date (${manifest.length} concepts)\n`);
} else {
  writeFileSync(OUT, body);
  console.log(`\n  wrote packages/exercises/src/manifest.ts (${manifest.length} concepts)\n`);
}
